"""Run the adversarial suite and render the scoreboard.

    make evals   # run it and refresh evals/SCOREBOARD.md

Exit code is 0 when every attack matched its documented expectation and 1
otherwise — an undocumented hole, a gap that got closed without the writeup
being updated, or a broken attack all fail the same way, because all three mean
the published number no longer describes the system.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from .attacks import ATTACKS
from .scoreboard import Result, Verdict, regressions, render, run_suite

_HEADER = """# Adversarial scoreboard

Generated by `make evals`. Committed so the number cannot rot silently: if the
harness changes, this file changes with it — and `make test` fails on any attack
that stops matching what is written here, in either direction.

**What the buckets mean.** *Blocked* is an attack the defense refused in the way
the attack said it would. *Known gap* is an attack that succeeds today, published
with the reason it is a stated boundary rather than an oversight. *Unexpected* is
an undocumented hole. *Errors* are attacks that broke — they say nothing about
the system and are never counted as wins.

Every attack states its property without reference to the implementation, and
names either the exception type that constitutes a legitimate refusal or the
independent evidence that the exploit really ran. See `evals/scoreboard.py` and
`evals/support.py` for why.
"""


def _table(results: list[Result]) -> str:
    rows = [
        "| attack | surface | verdict | control | what it does |",
        "|---|---|---|---|---|",
    ]
    marks = {
        Verdict.BLOCKED: "blocked",
        Verdict.SUCCEEDED: "succeeded",
        Verdict.ERROR: "ERROR",
    }
    control = {True: "yes", False: "FAILED", None: "—"}
    for result in sorted(results, key=lambda r: (r.attack.surface, r.attack.id)):
        flag = "" if result.as_expected else " **!**"
        rows.append(
            f"| `{result.attack.id}` | {result.attack.surface} | "
            f"{marks[result.verdict]}{flag} | {control[result.control_ok]} | "
            f"{result.attack.description} |"
        )
    return "\n".join(rows)


def _properties(results: list[Result]) -> str:
    lines = []
    for result in sorted(results, key=lambda r: (r.attack.surface, r.attack.id)):
        lines.append(f"### `{result.attack.id}`\n")
        lines.append(f"{result.attack.property}\n")
        if result.attack.known_gap:
            lines.append(f"**Known gap.** {result.attack.known_gap}\n")
    return "\n".join(lines)


def _document(results: list[Result]) -> str:
    blocked = [r for r in results if r.verdict is Verdict.BLOCKED and r.as_expected]
    gaps = [r for r in results if r.attack.known_gap and r.as_expected]
    holes = [
        r for r in results if r.verdict is Verdict.SUCCEEDED and not r.attack.known_gap
    ]
    errors = [r for r in results if r.verdict is Verdict.ERROR]
    parts = [
        _HEADER,
        f"## {len(blocked)} of {len(results)} attacks blocked\n",
        f"- **{len(blocked)}** blocked",
        f"- **{len(gaps)}** known gaps (published below with their rationale)",
        f"- **{len(holes)}** unexpected successes",
        f"- **{len(errors)}** errors\n",
        "## Results\n",
        _table(results),
        "\n## Properties and gaps\n",
        _properties(results),
    ]
    return "\n".join(parts).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", type=Path, help="path for the markdown artifact")
    args = parser.parse_args(argv)

    results = run_suite(ATTACKS)
    print(render(results))
    if args.write:
        args.write.write_text(_document(results))
        print(f"  wrote {args.write}\n")
    return 1 if regressions(results) else 0


if __name__ == "__main__":
    sys.exit(main())
